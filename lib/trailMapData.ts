export type MilestoneStatus = "done" | "current" | "next" | "future";

export type TrailMilestone = {
  id: string;
  label: string;
  status: MilestoneStatus;
  detail?: string;
};

export type FitLevel = "High match" | "Worth exploring" | "Consider" | "Broader stretch";

/** Only the two descriptive, non-scored factors stay as hand-authored
 * text. Everything else (cost, income, autonomy, AI exposure, demand,
 * etc.) is computed from `branchFactors` — see lib/trailMapScoring.ts. */
export type TrailMapFactors = {
  typicalTime: string;
  education: string;
};

export type TrailMapNode = {
  id: string;
  label: string;
};

export type TrailMapBranch = {
  id: string;
  title: string;
  icon: LucideIcon;
  fit: FitLevel;
  /** One complete short sentence for the dark selected-branch card — never
   * truncated, so it must stand on its own without an ellipsis. The longer
   * `whyItFits` stays in the right sidebar for the full explanation. */
  pitch: string;
  whyItFits: string;
  nodes: [TrailMapNode, TrailMapNode, TrailMapNode];
  factors: TrailMapFactors;
  /** Raw 0-5 inputs the sidebar/comparison scores are computed from. */
  branchFactors: BranchFactors;
  tradeoffs: string[];
  nextStep: { title: string; description: string };
};

export type TrailNote = {
  id: string;
  branchId: string;
  author: string;
  role: string;
  body: string;
  likes: number;
  verified?: boolean;
};

